/* eslint-env node */
/**
 * Builds src/assets/worldLand.ts, a single SVG path of the world's land masses in an
 * equirectangular 360x180 box (x = lon + 180, y = 90 - lat).
 *
 * Usage: node scripts/build_world_land.mjs path/to/land-110m.json
 * The input is the `land-110m.json` TopoJSON file from the `world-atlas` npm package
 * (Natural Earth, public domain).
 */
import { readFileSync, writeFileSync } from 'node:fs';

const topology = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const { scale, translate } = topology.transform;

const arcs = topology.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});

const ringPoints = (ring) =>
  ring.flatMap((index, position) => {
    const points = index < 0 ? [...arcs[~index]].reverse() : arcs[index];
    return position === 0 ? points : points.slice(1);
  });

const fmt = (value) => String(Math.round(value * 10) / 10);

/** Splits a ring wherever it jumps across the antimeridian, so no edge is drawn across the map. */
function splitAtAntimeridian(points) {
  const pieces = [[]];
  points.forEach((point, index) => {
    if (index > 0 && Math.abs(point[0] - points[index - 1][0]) > 180) pieces.push([]);
    pieces[pieces.length - 1].push(point);
  });
  return pieces;
}

const parts = [];
for (const geometry of topology.objects.land.geometries) {
  const polygons = geometry.type === 'Polygon' ? [geometry.arcs] : geometry.arcs;
  for (const polygon of polygons) {
    for (const ring of polygon) {
      for (const piece of splitAtAntimeridian(ringPoints(ring))) {
        const points = piece.map(([lon, lat]) => `${fmt(lon + 180)},${fmt(90 - lat)}`);
        const deduped = points.filter((point, index) => index === 0 || point !== points[index - 1]);
        if (deduped.length >= 3) parts.push(`M${deduped.join('L')}Z`);
      }
    }
  }
}

const source = `/** Generated by scripts/build_world_land.mjs from Natural Earth 1:110m land. Do not edit. */
export const WORLD_LAND_PATH =
  '${parts.join('')}';
`;
writeFileSync(new URL('../src/assets/worldLand.ts', import.meta.url), source);
console.error(`worldLand.ts: ${parts.length} rings, ${(source.length / 1024).toFixed(1)} kB`);
